'use client';

import { format } from 'date-fns';
import React from 'react';

interface TCCancelPrintProps {
    data: any[];
    schoolName?: string;
    schoolAddress?: string;
    schoolPhone?: string;
    logoUrl?: string;
}

export const TCCancelPrint = React.forwardRef<HTMLDivElement, TCCancelPrintProps>(
    ({ data, schoolName, schoolAddress, schoolPhone, logoUrl }, ref) => {
        const currentDate = format(new Date(), 'dd/MM/yyyy hh:mm a');

        return (
            <div ref={ref} className='printable-content min-h-full w-full bg-white p-8 font-serif text-black'>
                <style
                    dangerouslySetInnerHTML={{
                        __html: `
                    @media print {
                        @page { size: portrait; margin: 0; }
                        body { -webkit-print-color-adjust: exact; margin: 0; padding: 0; }
                        .no-print { display: none !important; }
                        .print-container { padding: 15mm; }
                    }
                `
                    }}
                />

                {/* Header */}
                <div className='print-container'>
                    <div className='mb-6 flex flex-col items-center border-black border-b-2 pb-4'>
                        <div className='flex w-full items-center justify-center gap-4'>
                            {logoUrl && <img src={logoUrl} alt='School Logo' className='h-20 w-20 object-contain' />}
                            <div className='text-center'>
                                <h1 className='font-bold text-2xl uppercase tracking-wide'>{schoolName}</h1>
                                <p className='font-medium text-sm'>{schoolAddress}</p>
                                <p className='font-medium text-sm'>Ph: {schoolPhone}</p>
                            </div>
                        </div>
                        <div className='mt-4 w-full text-center'>
                            <h2 className='inline-block border-black border-y px-4 py-1 font-bold text-lg'>Student TC Deleted Details -</h2>
                        </div>
                    </div>

                    {/* Table */}
                    <table className='w-full border-collapse border border-black text-[12px]'>
                        <thead>
                            <tr className='bg-gray-100'>
                                <th className='w-12 border border-black p-2 text-center'>Sl.No.</th>
                                <th className='border border-black p-2 text-left'>Student Details</th>
                                <th className='w-28 border border-black p-2 text-left'>TC.No.</th>
                                <th className='w-28 border border-black p-2 text-center'>TC Date</th>
                                <th className='border border-black p-2 text-left'>Reason For Deletion</th>
                                <th className='w-36 border border-black p-2 text-center'>Deleted Date</th>
                            </tr>
                        </thead>
                        <tbody>
                            {data.map((row, index) => (
                                <tr key={index}>
                                    <td className='border border-black p-2 text-center align-top'>{row.slNo}</td>
                                    <td className='border border-black p-2 align-top font-bold uppercase'>{row.studentDetails}</td>
                                    <td className='border border-black p-2 align-top'>{row.tcNo}</td>
                                    <td className='border border-black p-2 text-center align-top'>{row.tcDate}</td>
                                    <td className='border border-black p-2 align-top italic'>{row.reason}</td>
                                    <td className='border border-black p-2 text-center align-top'>{row.deletedDate}</td>
                                </tr>
                            ))}
                        </tbody>
                    </table>

                    {/* Footer */}
                    <div className='mt-8 flex items-end justify-between text-[10px] italic opacity-60'>
                        <div>Date: {currentDate}</div>
                        <div>Generated by Vaps Technosoft Pvt. Ltd.</div>
                    </div>
                </div>
            </div>
        );
    }
);

TCCancelPrint.displayName = 'TCCancelPrint';
